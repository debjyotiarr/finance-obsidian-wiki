#!/usr/bin/env python3
"""Rebuild `00-Inbox/Inbox Index.md`: one table of every inbox stub, sorted by
relevance then year, showing whether it has an abstract and a PDF on disk.

    python3 -I pipeline/build_inbox_index.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INBOX = ROOT / "00-Inbox"
OUT = INBOX / "Inbox Index.md"
ORDER = {"high": 0, "medium": 1, "low": 2, "": 1}


def field(text: str, key: str) -> str:
    m = re.search(rf"^{key}:[ \t]*(.*)$", text, re.M)
    return m.group(1).strip().strip('"') if m else ""


def main() -> int:
    rows = []
    for p in INBOX.rglob("*.md"):
        t = p.read_text(encoding="utf-8")
        if field(t, "status") != "inbox":
            continue
        rel = field(t, "relevance")
        has_abs = "verbatim from arXiv" in t
        pdf = (INBOX / "papers" / (p.stem + ".pdf")).exists()
        title = field(t, "title").replace("|", "/").replace("\\\"", "'")[:110]
        src = "arXiv" if "arxiv.org" in field(t, "url") else "other"
        rows.append((ORDER.get(rel, 1), -int(field(t, "year") or 0), rel or "unrated",
                     f"| {rel or 'unrated'} | {field(t, 'year')} | [[{p.stem}\\|{title}]] | {src} | "
                     f"{'yes' if has_abs else 'no'} | {'yes' if pdf else 'no'} | [link]({field(t, 'url')}) |"))
    rows.sort()
    body = "\n".join(r[3] for r in rows)
    OUT.write_text(f"""---
type: meta
tags: [inbox, index]
---

# Inbox Index

Every paper waiting for review ({len(rows)}), best first. Generated by `pipeline/build_inbox_index.py`; do not edit by hand. "PDF" means the file is in `00-Inbox/papers/` on this machine.

| Relevance | Year | Paper (opens the stub) | Source | Abstract | PDF | Web |
|---|---|---|---|---|---|---|
{body}
""", encoding="utf-8")
    print(f"indexed {len(rows)} stubs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
